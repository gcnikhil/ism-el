"""Final-paper regression: EVALUATION.md must stay tied to result files.

The document is generated by ``build_evaluation.py`` from results/*, but these
tests independently re-derive its quoted cells from the CSVs so a stale or
hand-edited document is caught.
"""

from __future__ import annotations

import json

import numpy as np
import pandas as pd
import pytest

from config import load_config, project_root
from paper_stats import DECOMPOSITION_COLUMNS

DOC_PATH = project_root() / "docs" / "EVALUATION.md"
FULL_DIR = project_root() / "results" / "full"
REAL_DIR = project_root() / "results" / "real"


def f(value: float, digits: int = 2) -> str:
    return f"{float(value):,.{digits}f}"


def _summary_cell(scenario: str, policy: str, metric: str) -> str:
    summary = pd.read_csv(FULL_DIR / "summary.csv")
    row = summary[(summary["scenario"] == scenario) & (summary["policy"] == policy)]
    assert len(row) == 1, (scenario, policy)
    return f"{f(row[f'{metric}_mean'].iloc[0])} ± {f(row[f'{metric}_std'].iloc[0])}"


def _sweep_cell(sweep: str, value: float, policy: str) -> str:
    frame = pd.read_csv(FULL_DIR / "sweep_summary.csv")
    row = frame[
        (frame["sweep"] == sweep)
        & (frame["sweep_value"] == value)
        & (frame["policy"] == policy)
    ]
    assert len(row) == 1, (sweep, value, policy)
    return f"{f(row['data_wait_ms_mean'].iloc[0])} ± {f(row['data_wait_ms_std'].iloc[0])}"


def _bootstrap_row(sweep: str, value: float | None, baseline: str) -> pd.Series:
    frame = pd.read_csv(FULL_DIR / "bootstrap_comparison.csv")
    matched = frame[
        (frame["sweep"] == sweep)
        & (frame["baseline"] == baseline)
        & (frame["scenario"] == "C")
        & (frame["metric"] == "data_wait_ms")
    ]
    if value is None:
        matched = matched[matched["sweep_value"].isna()]
    else:
        matched = matched[matched["sweep_value"] == value]
    assert len(matched) == 1, (sweep, value, baseline)
    return matched.iloc[0]


