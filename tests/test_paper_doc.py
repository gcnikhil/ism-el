def test_discussion_claims_match_the_data(doc: str) -> None:
    frame = pd.read_csv(FULL_DIR / "summary.csv")
    index = frame.set_index(["scenario", "policy"])["data_wait_ms_mean"]

    def wait(scenario: str, policy: str) -> float:
        return float(index.loc[(scenario, policy)])

    # Designed ties and the measured-compute ceiling: at the measured CPU step
    # time even AllSlow has zero uncovered data wait, so the whole matrix ties.
    assert all(wait("D", policy) == 0.0 for policy in frame["policy"].unique())
    assert wait("C", "clairvoyant") == wait("C", "lru")
    assert wait("C", "context_rules_noctx") == wait("C", "lru")
    assert float(frame["data_wait_ms_mean"].max()) == 0.0
    assert wait("C", "allslow") == 0.0
    # The uncached penalty shows up as throughput, not data wait.
    throughput = frame.set_index(["scenario", "policy"])["throughput_mean"]
    assert float(throughput.loc[("C", "allslow")]) < float(throughput.loc[("C", "lru")])

    # Every policy appears in the main table under its display name.
    from app.data import DISPLAY_NAMES

    lower_doc = doc.lower()
    for policy in frame["policy"].unique():
        name = DISPLAY_NAMES.get(str(policy), str(policy)).split(" (")[0]
        assert name.lower() in lower_doc, name


